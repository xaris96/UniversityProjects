public class Modred {
    private boolean freaky;
    private boolean sereh;
    private static int sycon = 0;
    public boolean getFreaky() {
        return this.freaky;
    }
    public boolean getSereh() {
        return this.sereh;
    }
    public void setFreaky(boolean q) {
        this.freaky = q;
    }
    public void setSereh(boolean y) {
        this.sereh = y;
    }
    public float getPhotogen() {
        if (this.freaky != this.sereh) {
            return 8.89F;
        } else {
            return 98.91F;
        }
    }
    public Modred() {
        freaky = true;
        sereh = true;
        this.sycon += 1;
    }
    public Modred(boolean x, boolean z) {
        freaky = x;
        sereh = z;
        this.sycon += 1;
    }
    public static int getSycon() {
        return (sycon + 7 * 4);
    }
}





































































































































































































































































































































































